-- Payments: append-only ledger. A mistake is corrected by a reversal row (negative amount, reason,
-- link to the original), never by editing or deleting.

create table public.payments (
  id uuid primary key default gen_random_uuid(),
  client_id uuid not null references public.clients (id) on delete restrict,
  kind text not null check (kind in ('payment', 'reversal')),
  amount integer not null,
  method text not null check (method in ('cash', 'kaspi', 'transfer')),
  -- A reversal repeats the period of the payment it cancels (enforced by trigger below).
  period_start date not null,
  period_end date not null,
  reverses_id uuid unique,
  reason text,
  -- Generated by the payment form when it opens; a resubmission carries the same key.
  idempotency_key uuid not null unique,
  created_by uuid not null default auth.uid() references public.staff (id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint payments_period_order check (period_start <= period_end),
  constraint payments_kind_shape check (
    (kind = 'payment' and amount > 0 and reverses_id is null and reason is null)
    or (
      kind = 'reversal'
      and amount < 0
      and reverses_id is not null
      and reason is not null
      and char_length(btrim(reason)) between 1 and 500
    )
  ),
  -- Lets reversals reference (id, client_id) so a reversal can only target the same client.
  constraint payments_id_client_unique unique (id, client_id),
  constraint payments_reverses_same_client foreign key (reverses_id, client_id)
    references public.payments (id, client_id) on delete restrict
);

comment on table public.payments is
  'Append-only. Corrections are reversal rows; UPDATE/DELETE/TRUNCATE raise.';

alter table public.payments enable row level security;

create index payments_client_period_idx on public.payments (client_id, period_end desc);

-- The original is read without RLS so the check does not depend on what the caller may see.
create function public.check_reversal()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  original public.payments%rowtype;
begin
  if new.kind <> 'reversal' then
    return new;
  end if;

  select * into original from public.payments p where p.id = new.reverses_id;

  if original.kind <> 'payment' then
    raise exception 'a reversal can only cancel a payment' using errcode = '23514';
  end if;
  if new.amount <> -original.amount then
    raise exception 'reversal amount must be the opposite of the original payment'
      using errcode = '23514';
  end if;
  if new.period_start <> original.period_start or new.period_end <> original.period_end then
    raise exception 'reversal period must match the original payment' using errcode = '23514';
  end if;

  return new;
end;
$$;

create trigger payments_check_reversal
  before insert on public.payments
  for each row execute function public.check_reversal();

create trigger payments_append_only
  before update or delete on public.payments
  for each row execute function public.forbid_change();

create trigger payments_no_truncate
  before truncate on public.payments
  for each statement execute function public.forbid_change();

-- D-09 default: an admin sees individual payment amounts (client card, payment form), but not
-- totals or reports; those are owner-only functions in the reports step.
create policy payments_select on public.payments
  for select to authenticated
  using ((select public.current_staff_role()) in ('owner', 'admin'));

-- A policy on payments cannot query payments itself (Postgres reports infinite recursion), so the
-- "own payment made less than 10 minutes ago" check reads the original through a definer function.
create function public.is_own_recent_payment(p_payment_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.payments p
    where p.id = p_payment_id
      and p.kind = 'payment'
      and p.created_by = (select auth.uid())
      and p.created_at > now() - interval '10 minutes'
  );
$$;

-- Any reversal by the owner; an admin may only cancel their own payment within 10 minutes
-- (step 07, "cancel right away").
create policy payments_insert on public.payments
  for insert to authenticated
  with check (
    created_by = (select auth.uid())
    and (
      (kind = 'payment' and (select public.current_staff_role()) in ('owner', 'admin'))
      or (kind = 'reversal' and (select public.current_staff_role()) = 'owner')
      or (
        kind = 'reversal'
        and (select public.current_staff_role()) = 'admin'
        and public.is_own_recent_payment(reverses_id)
      )
    )
  );
